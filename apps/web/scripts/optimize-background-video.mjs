import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = dirname(fileURLToPath(import.meta.url));
const backgroundsDir = join(__dirname, "../public/backgrounds");
const sourceDir = join(backgroundsDir, "_source");
const lqipPath = join(__dirname, "../lib/simulator/background-lqip.ts");

const DISPLAY_EDGE = 1920;
const DISPLAY_FPS = 30;
const DISPLAY_CRF = 26;
const THUMB_EDGE = 96;
const THUMB_QUALITY = 75;
const LQIP_EDGE = 16;
const POSTER_EDGE = 1920;
const POSTER_QUALITY = 80;

const PRESETS = ["bike-trail", "bike-city", "city-day", "city-night"];

function findSourcePath(name) {
  const candidates = [
    join(sourceDir, `${name}.mp4`),
    join(sourceDir, `${name}_cycling.mp4`),
    join(sourceDir, `trail_cycling.mp4`),
    join(backgroundsDir, `${name}.mp4`),
  ];
  for (const path of candidates) {
    try {
      readFileSync(path);
      return path;
    } catch {
      // try next
    }
  }
  throw new Error(`No source video found for preset "${name}"`);
}

function runFfmpeg(args) {
  execFileSync("ffmpeg", ["-y", ...args], { stdio: "inherit" });
}

function formatKb(bytes) {
  return `${Math.round(bytes / 1024)}KB`;
}

async function optimizePreset(name) {
  const sourcePath = findSourcePath(name);
  const mp4Out = join(backgroundsDir, `${name}.mp4`);
  const posterOut = join(backgroundsDir, `${name}-poster.webp`);
  const thumbOut = join(backgroundsDir, `${name}-thumb.webp`);
  const posterFrame = join(backgroundsDir, `${name}-poster-frame.png`);

  mkdirSync(sourceDir, { recursive: true });

  runFfmpeg([
    "-i",
    sourcePath,
    "-vf",
    `scale='min(${DISPLAY_EDGE},iw)':-2,fps=${DISPLAY_FPS}`,
    "-c:v",
    "libx264",
    "-profile:v",
    "high",
    "-crf",
    String(DISPLAY_CRF),
    "-movflags",
    "+faststart",
    "-an",
    mp4Out,
  ]);

  runFfmpeg(["-ss", "0", "-i", sourcePath, "-frames:v", "1", "-update", "1", posterFrame]);

  const posterBuffer = await sharp(posterFrame)
    .resize(POSTER_EDGE, POSTER_EDGE, { fit: "inside", withoutEnlargement: true })
    .webp({ quality: POSTER_QUALITY })
    .toBuffer();
  const thumbBuffer = await sharp(posterFrame)
    .resize(THUMB_EDGE, THUMB_EDGE, { fit: "cover" })
    .webp({ quality: THUMB_QUALITY })
    .toBuffer();

  writeFileSync(posterOut, posterBuffer);
  writeFileSync(thumbOut, thumbBuffer);

  try {
    unlinkSync(posterFrame);
  } catch {
    // temp frame already removed
  }

  const lqipBuffer = await sharp(posterBuffer)
    .resize(LQIP_EDGE, LQIP_EDGE, { fit: "cover" })
    .jpeg({ quality: 60 })
    .toBuffer();

  const mp4Size = readFileSync(mp4Out).length;
  console.log(
    `${name}: video ${formatKb(mp4Size)}, poster ${formatKb(posterBuffer.length)}, thumb ${formatKb(thumbBuffer.length)}`,
  );

  return { name, lqip: `data:image/jpeg;base64,${lqipBuffer.toString("base64")}` };
}

function readExistingLqip() {
  const entries = {};
  try {
    const raw = readFileSync(lqipPath, "utf8");
    for (const match of raw.matchAll(/^\s+"?([\w-]+)"?:\s+"(data:[^"]+)"/gm)) {
      entries[match[1]] = match[2];
    }
    return entries;
  } catch {
    return entries;
  }
}

function writeLqipFile(entries) {
  const lines = Object.entries(entries).map(([name, lqip]) => `  "${name}": "${lqip}",`);
  const contents = `// tiny jpeg placeholders for preset photo/video blur-up (16×16, ~900 chars each).
// generated by scripts/optimize-backgrounds.mjs and optimize-background-video.mjs — do not edit by hand.
export const BACKGROUND_LQIP = {
${lines.join("\n")}
} as const;
`;
  writeFileSync(lqipPath, contents);
}

const lqipEntries = readExistingLqip();
for (const name of PRESETS) {
  const { name: presetName, lqip } = await optimizePreset(name);
  lqipEntries[presetName] = lqip;
}

writeLqipFile(lqipEntries);
console.log("optimized video background presets into /public/backgrounds");
