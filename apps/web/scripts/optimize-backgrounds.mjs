import { mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = dirname(fileURLToPath(import.meta.url));
const backgroundsDir = join(__dirname, "../public/backgrounds");
const sourceDir = join(backgroundsDir, "_source");
const lqipPath = join(__dirname, "../lib/simulator/background-lqip.ts");

const DISPLAY_EDGE = 1920;
const DISPLAY_QUALITY = 80;
const THUMB_EDGE = 96;
const THUMB_QUALITY = 75;
const LQIP_EDGE = 16;

const PRESETS = ["alps", "alps2", "beach"];

function scaledDimensions(width, height, edge) {
  const longest = Math.max(width, height);
  const scale = longest > edge ? edge / longest : 1;
  return {
    width: Math.max(1, Math.round(width * scale)),
    height: Math.max(1, Math.round(height * scale)),
  };
}

async function encodeWebp(input, edge, quality) {
  const meta = await input.metadata();
  const { width, height } = scaledDimensions(meta.width, meta.height, edge);
  return input
    .clone()
    .resize(width, height, { fit: "inside", withoutEnlargement: true })
    .webp({ quality })
    .toBuffer();
}

function findSourcePath(name) {
  const candidates = [
    join(sourceDir, `${name}.jpg`),
    join(sourceDir, `${name}.jpeg`),
    join(sourceDir, `${name}.png`),
    join(backgroundsDir, `${name}.jpg`),
    join(backgroundsDir, `${name}.jpeg`),
    join(backgroundsDir, `${name}.png`),
  ];
  for (const path of candidates) {
    try {
      readFileSync(path);
      return path;
    } catch {
      // try next
    }
  }
  throw new Error(`No source image found for preset "${name}"`);
}

function formatKb(bytes) {
  return `${Math.round(bytes / 1024)}KB`;
}

async function optimizePreset(name) {
  const sourcePath = findSourcePath(name);
  const input = sharp(sourcePath);
  const [display, thumb] = await Promise.all([
    encodeWebp(input, DISPLAY_EDGE, DISPLAY_QUALITY),
    encodeWebp(input, THUMB_EDGE, THUMB_QUALITY),
  ]);

  writeFileSync(join(backgroundsDir, `${name}.webp`), display);
  writeFileSync(join(backgroundsDir, `${name}-thumb.webp`), thumb);

  const lqipBuffer = await sharp(display)
    .resize(LQIP_EDGE, LQIP_EDGE, { fit: "cover" })
    .jpeg({ quality: 60 })
    .toBuffer();

  console.log(`${name}: display ${formatKb(display.length)}, thumb ${formatKb(thumb.length)}`);

  return { name, lqip: `data:image/jpeg;base64,${lqipBuffer.toString("base64")}` };
}

function readExistingLqip() {
  try {
    const raw = readFileSync(lqipPath, "utf8");
    const entries = {};
    for (const match of raw.matchAll(/^\s+"?([\w-]+)"?:\s+"(data:[^"]+)"/gm)) {
      entries[match[1]] = match[2];
    }
    return entries;
  } catch {
    return {};
  }
}

function writeLqipFile(entries) {
  const lines = Object.entries(entries).map(([name, lqip]) => `  "${name}": "${lqip}",`);
  const contents = `// tiny jpeg placeholders for preset photo/video blur-up (16×16, ~900 chars each).
// generated by scripts/optimize-backgrounds.mjs and optimize-background-video.mjs — do not edit by hand.
export const BACKGROUND_LQIP = {
${lines.join("\n")}
} as const;
`;
  writeFileSync(lqipPath, contents);
}

function removeLegacyOutputs() {
  for (const file of readdirSync(backgroundsDir)) {
    if (file.endsWith(".jpg") || file.endsWith(".jpeg") || file.endsWith("-iframe.webp")) {
      unlinkSync(join(backgroundsDir, file));
    }
  }
}

mkdirSync(sourceDir, { recursive: true });

const lqipEntries = readExistingLqip();
for (const name of PRESETS) {
  const { name: presetName, lqip } = await optimizePreset(name);
  lqipEntries[presetName] = lqip;
}

writeLqipFile(lqipEntries);
removeLegacyOutputs();
console.log("optimized background presets into /public/backgrounds");
